export function getBooksByCategory(category: string): Book[] {
  switch (category) {
    case "featured":
      return books.filter((b) => b.featured);
    case "new":
      return books.filter((b) => b.isNew);
    case "popular":
      return books.filter((b) => b.rating >= 4.5);
    case "free":
      return books.filter((b) => b.access === "free");
    case "premium":
      return books.filter((b) => b.access === "premium");
    case "rwandan":
      return books.filter((b) => b.isRwandan);
    case "african":
      return books.filter((b) => b.isAfrican);
    default:
      return books;
  }
}

export function getBookBySlug(slug: string): Book | undefined {
  return books.find((b) => b.slug === slug);
}

export function getRelatedBooks(book: Book, limit = 6): Book[] {
  return books
    .filter(
      (b) =>
        b.id !== book.id &&
        (b.genre === book.genre || b.isRwandan === book.isRwandan)
    )
    .slice(0, limit);
}
