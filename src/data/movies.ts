export function getMoviesByCategory(category: string): Movie[] {
  switch (category) {
    case "trending":
      return movies.filter((m) => m.trending);
    case "new":
      return movies.filter((m) => m.isNew);
    case "rwandan":
      return movies.filter((m) => m.isRwandan);
    case "african":
      return movies.filter((m) => m.isAfrican);
    case "free":
      return movies.filter((m) => m.freeToWatch);
    case "premium":
      return movies.filter((m) => m.access === "premium");
    case "featured":
      return movies.filter((m) => m.featured);
    default:
      return movies;
  }
}

export function getMovieBySlug(slug: string): Movie | undefined {
  return movies.find((m) => m.slug === slug);
}

export function getRelatedMovies(movie: Movie, limit = 6): Movie[] {
  return movies
    .filter(
      (m) =>
        m.id !== movie.id &&
        m.genres.some((g) => movie.genres.includes(g))
    )
    .slice(0, limit);
}
